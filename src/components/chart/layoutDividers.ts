export function getLayoutSvgString(layoutId: ChartLayoutId, size = 18): string {
  const dividers = LAYOUT_DIVIDERS[layoutId] ?? [];
  const lines = dividers
    .map(
      ([x1, y1, x2, y2]) =>
        `<line x1="${x1}" y1="${y1}" x2="${x2}" y2="${y2}" stroke="currentColor" stroke-width="1.2" stroke-linecap="square" />`
    )
    .join('');
  return `<svg width="${size}" height="${size}" viewBox="0 0 28 28" fill="none" xmlns="http://www.w3.org/2000/svg"><rect x="3" y="3" width="22" height="22" rx="2" stroke="currentColor" stroke-width="1.5" />${lines}</svg>`;
}

